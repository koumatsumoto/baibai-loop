@pytest.fixture
def master_capture():
    store = _Store()
    assert _refresh(store, "JP", (_JP,)) == "updated"
    assert _refresh(store, "US", (_US,)) == "updated"
    # A checked, noncanonical-but-valid payload must not be regenerated by the pin.
    payload = b" \n" + store.values[LISTING_MASTER_CURRENT_KEY].body + b"\n"
    return payload, read_current_listing_master(store)


@pytest.mark.parametrize(
    "state",
    ["valid", "absent", "denied", "corrupt", "oversize", "truncated", "unknown_schema", "race"],
)
def test_pin_cli_uses_one_checked_r2_response_and_no_other_object(
    tmp_path, monkeypatch, capsys, caplog, master_capture, state
):
    payload, expected = master_capture
    private = "SYNTHETIC_PRIVATE_CAPTURE"
    monkeypatch.setenv("R2_ACCOUNT_ID", "a" * 32)
    monkeypatch.setenv("R2_ACCESS_KEY_ID", private)
    monkeypatch.setenv("R2_SECRET_ACCESS_KEY", private)
    monkeypatch.setenv("R2_STORES_BUCKET", "master-fixture")
    monkeypatch.setenv("R2_STOP_ON_REJECTION", "0")
    monkeypatch.delenv("R2_REJECTION_STOP_FILE", raising=False)
    output = tmp_path / "run" / (private + ".json")
    if state == "unknown_schema":
        payload = b'{"future":"' + private.encode() + b'"}'

    read_sizes = []

    class Body(BytesIO):
        def read(self, size=-1):
            read_sizes.append(size)
            return super().read(size)

    body = Body(payload)
    calls = []
    size = (
        LISTING_MASTER_MAX_BYTES + 1
        if state == "oversize"
        else len(payload) + (state == "truncated")
    )

    def get_object(*, Bucket, Key):
        calls.append((Bucket, Key))
        if state in ("absent", "denied"):
            raise ClientError(
                {
                    "Error": {"Code": "NoSuchKey", "Message": private},
                    "ResponseMetadata": {"HTTPStatusCode": 404 if state == "absent" else 403},
                },
                "GetObject",
            )
        if state == "race":
            output.parent.mkdir()
            output.write_bytes(b"another snapshot already pinned")
        return {
            "Body": body,
            "ETag": '"synthetic-etag"',
            "ContentLength": size,
            "Metadata": {"sha256": "0" * 64 if state == "corrupt" else sha256(payload).hexdigest()},
        }

    def client(self, *, single_attempt):
        assert single_attempt is True
        # Deliberately does not implement HEAD, PUT, or an alternate GET route.
        return SimpleNamespace(get_object=get_object)

    monkeypatch.setattr(Boto3R2Store, "_client", client)
    result = handoff.main(["--output", str(output)])
    assert calls == [("master-fixture", LISTING_MASTER_CURRENT_KEY)]
    captured = capsys.readouterr()
    assert not captured.out
    assert private not in captured.err + caplog.text

    if state == "valid":
        assert result == 0
        assert not captured.err
        assert output.read_bytes() == payload
        assert S_IMODE(output.stat().st_mode) == 0o600
        assert list(output.parent.iterdir()) == [output]
        assert read_local_listing_master(output) == expected
        assert read_local_listing_master(output)["JP"] == expected["JP"]
        assert handoff.main(["--output", str(output)]) == 1
        assert calls == [("master-fixture", LISTING_MASTER_CURRENT_KEY)]
        assert output.read_bytes() == payload
    else:
        assert result == 1
        if state == "race":
            assert output.read_bytes() == b"another snapshot already pinned"
            assert list(output.parent.iterdir()) == [output]
        else:
            assert not output.exists()
    if state == "denied":
        assert captured.err == "listing master pin failed: R2Error\n"
    if state == "absent":
        assert captured.err == "listing master pin failed: FileNotFoundError\n"
    if state in ("absent", "denied", "oversize"):
        assert not read_sizes
    else:
        assert read_sizes == [size + 1]
    if state not in ("absent", "denied"):
        assert body.closed


def test_pin_wont_follow_or_replace_an_existing_broken_symlink(tmp_path):
    output = tmp_path / "pin.json"
    absent = tmp_path / "outside.json"
    output.symlink_to(absent)

    class NoGet:
        def get_checked_object(self, key, *, max_bytes):
            pytest.fail("pre-existing output must be rejected without a remote request")

    with pytest.raises(FileExistsError):
        handoff.pin_current_listing_master(NoGet(), output=output)
    assert output.is_symlink()
    assert not absent.exists()
